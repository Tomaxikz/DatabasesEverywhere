//! The standalone node config: generated identity plus the wizard's choices,
//! with every other setting taken from the bundled `config/example.yml`.
//!
//! The YAML is built as a structured value rather than text, so the example
//! stays the single list of defaults and new settings there flow through.

use std::fmt;

use anyhow::{Context, anyhow};
use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
use secrecy::{ExposeSecret, SecretString};
use yaml_serde::{Mapping, Value};

use crate::databases::protocol::Protocol;

const EXAMPLE_CONFIG: &str =
    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/config/example.yml"));
/// The MongoDB 7 tag the example documents for kernels 6.19 and newer.
pub(super) const MONGODB_KERNEL_FALLBACK: &str = "mongo:7.0.37";
const SECRET_BYTES: usize = 32;
const HEADER: &str = "\
# DatabasesEverywhere node config, generated by `dbev --cli` (standalone mode).
# Settings the wizard did not ask about use the defaults of config/example.yml,
# which documents each of them. Keep this file private: root-owned, mode 0600.
";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum BindScope {
    /// Only clients on this machine reach the gateways.
    Local,
    /// Every interface; clients on the network reach the gateways.
    Network,
}

impl BindScope {
    pub(super) fn host(self) -> &'static str {
        match self {
            Self::Local => "127.0.0.1",
            Self::Network => "0.0.0.0",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum DiskMode {
    Auto,
    ProjectQuota,
    FuseQuota,
    SoftScanner,
}

impl DiskMode {
    pub(super) const ALL: [Self; 4] = [
        Self::Auto,
        Self::ProjectQuota,
        Self::FuseQuota,
        Self::SoftScanner,
    ];

    pub(super) fn as_str(self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::ProjectQuota => "project_quota",
            Self::FuseQuota => "fuse_quota",
            Self::SoftScanner => "soft_scanner",
        }
    }

    pub(super) fn description(self) -> &'static str {
        match self {
            Self::Auto => "native quotas when the filesystem has them, else FuseQuota",
            Self::ProjectQuota => "native XFS/Btrfs/ZFS/ext4/f2fs quotas; fails if not ready",
            Self::FuseQuota => "hard limits through a FUSE helper per database",
            Self::SoftScanner => "measures usage and stops a database near its limit",
        }
    }
}

/// What the operator chose in the wizard.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct Choices {
    pub engines: Vec<Protocol>,
    pub public_host: String,
    pub scope: BindScope,
    pub disk: DiskMode,
    pub api_enabled: bool,
}

/// Node identity and secrets; a panel generates these in managed mode.
pub(super) struct NodeIdentity {
    pub uuid: String,
    pub token_id: String,
    pub token: SecretString,
    pub jwt_signing_key: SecretString,
}

impl fmt::Debug for NodeIdentity {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("NodeIdentity")
            .field("uuid", &self.uuid)
            .field("token_id", &self.token_id)
            .finish_non_exhaustive()
    }
}

impl NodeIdentity {
    pub(super) fn generate() -> Self {
        let token_id = hex::encode(random_bytes(8));
        Self {
            uuid: uuid::Uuid::new_v4().to_string(),
            token_id: format!("dbev-{token_id}"),
            token: SecretString::from(URL_SAFE_NO_PAD.encode(random_bytes(SECRET_BYTES))),
            jwt_signing_key: SecretString::from(URL_SAFE_NO_PAD.encode(random_bytes(SECRET_BYTES))),
        }
    }
}

fn random_bytes(count: usize) -> Vec<u8> {
    use aws_lc_rs::rand::{SecureRandom, SystemRandom};

    let mut bytes = vec![0_u8; count];
    SystemRandom::new()
        .fill(&mut bytes)
        .expect("system CSPRNG failed to produce node secrets");
    bytes
}

/// The complete config document, ready to write.
pub(super) fn render(
    choices: &Choices,
    identity: &NodeIdentity,
    kernel: Option<&str>,
) -> anyhow::Result<String> {
    let document = standalone_config(choices, identity, kernel)?;
    let yaml = yaml_serde::to_string(&document).context("failed to encode the config")?;
    Ok(format!("{HEADER}{yaml}"))
}

pub(super) fn standalone_config(
    choices: &Choices,
    identity: &NodeIdentity,
    kernel: Option<&str>,
) -> anyhow::Result<Value> {
    let mut root: Mapping =
        yaml_serde::from_str(EXAMPLE_CONFIG).context("the bundled example config is invalid")?;
    root.insert("uuid".into(), identity.uuid.as_str().into());
    root.insert("token_id".into(), identity.token_id.as_str().into());
    root.insert("token".into(), identity.token.expose_secret().into());
    root.insert(
        "jwt_signing_key".into(),
        identity.jwt_signing_key.expose_secret().into(),
    );
    // Standalone nodes have no panel.
    root.shift_remove("remote");
    // The example points at one site's certificates; no listener uses TLS here.
    let mut tls = Mapping::new();
    tls.insert("cert".into(), "".into());
    tls.insert("key".into(), "".into());
    root.insert("tls".into(), Value::Mapping(tls));

    for protocol in Protocol::ALL {
        let listener = section(&mut root, protocol.as_str())?;
        listener.insert("enabled".into(), choices.engines.contains(&protocol).into());
        rebind(listener, "bind", choices.scope)?;
        if protocol == Protocol::Clickhouse {
            rebind(listener, "http_bind", choices.scope)?;
        }
    }

    let api = section(&mut root, "api")?;
    let mut example = std::mem::take(api);
    // The wizard's answer replaces the example's `enabled`, kept first.
    example.shift_remove("enabled");
    let mut settings = Mapping::new();
    settings.insert("enabled".into(), choices.api_enabled.into());
    settings.extend(example);
    if choices.api_enabled {
        settings.insert("host".into(), choices.scope.host().into());
    }
    *api = settings;

    section(&mut root, "disk")?.insert("mode".into(), choices.disk.as_str().into());
    let images = section(&mut root, "images")?;
    let mongodb = images
        .get("mongodb")
        .and_then(Value::as_str)
        .ok_or_else(|| anyhow!("the example config has no images.mongodb"))?;
    let mongodb = mongodb_image(mongodb, kernel).to_string();
    images.insert("mongodb".into(), mongodb.into());
    Ok(Value::Mapping(root))
}

fn section<'a>(root: &'a mut Mapping, name: &str) -> anyhow::Result<&'a mut Mapping> {
    root.get_mut(name)
        .and_then(Value::as_mapping_mut)
        .ok_or_else(|| anyhow!("the example config has no {name} section"))
}

/// Keeps the example's port and replaces its address with the chosen scope.
fn rebind(listener: &mut Mapping, key: &str, scope: BindScope) -> anyhow::Result<()> {
    let port = listener
        .get(key)
        .and_then(Value::as_str)
        .and_then(|bind| bind.rsplit_once(':'))
        .map(|(_, port)| port.to_string())
        .ok_or_else(|| anyhow!("the example config has no {key} address with a port"))?;
    listener.insert(key.into(), format!("{}:{port}", scope.host()).into());
    Ok(())
}

/// The example's image, or the MongoDB 7 fallback where config validation
/// (`check_mongodb_kernel`) rejects MongoDB 8+: Linux 6.19 and newer.
pub(super) fn mongodb_image<'a>(example: &'a str, kernel: Option<&str>) -> &'a str {
    let numbers = |text: &str| -> Vec<u32> {
        text.split(|character: char| !character.is_ascii_digit())
            .filter(|part| !part.is_empty())
            .take(2)
            .map(|part| part.parse().unwrap_or(u32::MAX))
            .collect()
    };
    let new_kernel = kernel.is_some_and(|release| numbers(release) >= vec![6, 19]);
    let name = example.split_once('@').map_or(example, |(name, _)| name);
    let tag = name
        .rsplit_once(':')
        .filter(|(_, tag)| !tag.contains('/'))
        .map_or("latest", |(_, tag)| tag);
    let mongodb_8 = tag == "latest" || numbers(tag).first().is_some_and(|major| *major >= 8);
    if new_kernel && mongodb_8 {
        MONGODB_KERNEL_FALLBACK
    } else {
        example
    }
}

/// The MongoDB image the generated config will use on this kernel.
pub(super) fn chosen_mongodb_image(kernel: Option<&str>) -> String {
    yaml_serde::from_str::<Value>(EXAMPLE_CONFIG)
        .ok()
        .and_then(|example| {
            example
                .get("images")?
                .get("mongodb")?
                .as_str()
                .map(|image| mongodb_image(image, kernel).to_string())
        })
        .unwrap_or_else(|| MONGODB_KERNEL_FALLBACK.to_string())
}

pub(super) fn kernel_release() -> Option<String> {
    std::fs::read_to_string("/proc/sys/kernel/osrelease")
        .ok()
        .map(|release| release.trim().to_string())
        .filter(|release| !release.is_empty())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Config;

    fn choices() -> Choices {
        Choices {
            engines: vec![Protocol::Postgres, Protocol::Clickhouse],
            public_host: "db.example.com".to_string(),
            scope: BindScope::Network,
            disk: DiskMode::SoftScanner,
            api_enabled: false,
        }
    }

    fn generated(choices: &Choices, kernel: Option<&str>) -> Value {
        let identity = NodeIdentity::generate();
        let text = render(choices, &identity, kernel).unwrap();
        assert!(text.starts_with("# DatabasesEverywhere node config"));
        yaml_serde::from_str(&text).unwrap()
    }

    fn text<'a>(value: &'a Value, path: &[&str]) -> &'a str {
        let mut current = value;
        for key in path {
            current = &current[*key];
        }
        current
            .as_str()
            .unwrap_or_else(|| panic!("{path:?} is not text"))
    }

    #[test]
    fn identities_are_random_long_and_distinct() {
        let first = NodeIdentity::generate();
        let second = NodeIdentity::generate();
        let token = first.token.expose_secret();
        let key = first.jwt_signing_key.expose_secret();
        assert!(token.len() >= 32 && key.len() >= 32);
        assert_eq!(URL_SAFE_NO_PAD.decode(token).unwrap().len(), SECRET_BYTES);
        assert_ne!(token, key);
        assert_ne!(token, second.token.expose_secret());
        assert_ne!(first.uuid, second.uuid);
        assert_ne!(first.token_id, second.token_id);
        uuid::Uuid::parse_str(&first.uuid).unwrap();
        assert!(!format!("{first:?}").contains(token));
    }

    #[test]
    fn generated_config_carries_choices_identity_and_no_panel() {
        let choices = choices();
        let identity = NodeIdentity::generate();
        let config = standalone_config(&choices, &identity, Some("6.12.0")).unwrap();
        assert!(config.get("remote").is_none());
        assert_eq!(text(&config, &["uuid"]), identity.uuid);
        assert_eq!(text(&config, &["token_id"]), identity.token_id);
        assert_eq!(text(&config, &["token"]), identity.token.expose_secret());
        assert_eq!(
            text(&config, &["jwt_signing_key"]),
            identity.jwt_signing_key.expose_secret()
        );
        assert_eq!(text(&config, &["tls", "cert"]), "");
        assert_eq!(config["api"]["enabled"], Value::Bool(false));
        assert_eq!(text(&config, &["api", "host"]), "127.0.0.1");
        assert_eq!(text(&config, &["disk", "mode"]), "soft_scanner");
        for protocol in Protocol::ALL {
            let listener = &config[protocol.as_str()];
            assert_eq!(
                listener["enabled"],
                Value::Bool(choices.engines.contains(&protocol)),
                "{protocol}"
            );
            assert!(text(&config, &[protocol.as_str(), "bind"]).starts_with("0.0.0.0:"));
        }
        assert_eq!(text(&config, &["postgres", "bind"]), "0.0.0.0:5434");
        assert_eq!(text(&config, &["clickhouse", "http_bind"]), "0.0.0.0:8123");
    }

    #[test]
    fn every_example_setting_is_kept_in_order() {
        let example: Value = yaml_serde::from_str(EXAMPLE_CONFIG).unwrap();
        let config = generated(&choices(), None);
        let (Value::Mapping(example), Value::Mapping(config)) = (&example, &config) else {
            panic!("configs are mappings");
        };
        let sections = |mapping: &Mapping| {
            mapping
                .keys()
                .filter(|key| *key != "remote")
                .cloned()
                .collect::<Vec<_>>()
        };
        assert_eq!(sections(config), sections(example));
        for (key, value) in example {
            if key == "remote" {
                continue;
            }
            assert!(config.contains_key(key), "{key:?} is missing");
            if let Value::Mapping(section) = value {
                for nested in section.keys() {
                    assert!(config[key].get(nested).is_some(), "{key:?}.{nested:?}");
                }
            }
        }
        assert_eq!(
            config["security"]["api_rate_limit_per_minute"],
            example["security"]["api_rate_limit_per_minute"]
        );
    }

    #[test]
    fn open_api_follows_the_bind_scope() {
        let mut choices = choices();
        choices.api_enabled = true;
        let config = generated(&choices, None);
        assert_eq!(config["api"]["enabled"], Value::Bool(true));
        assert_eq!(text(&config, &["api", "host"]), "0.0.0.0");
        choices.scope = BindScope::Local;
        let config = generated(&choices, None);
        assert_eq!(text(&config, &["api", "host"]), "127.0.0.1");
        assert_eq!(text(&config, &["redis", "bind"]), "127.0.0.1:6380");
    }

    #[test]
    fn mongodb_falls_back_to_7_on_kernels_it_cannot_run_on() {
        assert_eq!(mongodb_image("mongo:8.3.4", Some("6.18.20")), "mongo:8.3.4");
        assert_eq!(mongodb_image("mongo:8.3.4", None), "mongo:8.3.4");
        for kernel in ["6.19.0", "7.3.0-2-cachyos", "10.0"] {
            assert_eq!(
                mongodb_image("mongo:8.3.4", Some(kernel)),
                MONGODB_KERNEL_FALLBACK
            );
            assert_eq!(mongodb_image("mongo:7.0.40", Some(kernel)), "mongo:7.0.40");
            assert_eq!(
                mongodb_image("registry.local:5000/mongo:latest", Some(kernel)),
                MONGODB_KERNEL_FALLBACK
            );
        }
        let config = generated(&choices(), Some("7.0.1"));
        assert_eq!(
            text(&config, &["images", "mongodb"]),
            MONGODB_KERNEL_FALLBACK
        );
        assert_eq!(chosen_mongodb_image(Some("7.0.1")), MONGODB_KERNEL_FALLBACK);
        // The fallback must stay an image operators allowed in the example.
        let allowed = config["images"]["allowed"]["mongodb"]
            .as_sequence()
            .unwrap();
        assert!(allowed.contains(&Value::from(MONGODB_KERNEL_FALLBACK)));
    }

    #[test]
    fn generated_configs_pass_validation() {
        let kernel = kernel_release();
        for api_enabled in [false, true] {
            for disk in DiskMode::ALL {
                let mut choices = choices();
                choices.api_enabled = api_enabled;
                choices.disk = disk;
                let identity = NodeIdentity::generate();
                let yaml = render(&choices, &identity, kernel.as_deref()).unwrap();
                let config: Config = yaml_serde::from_str(&yaml).unwrap();
                crate::config::validate::validate_config(&config).unwrap();
            }
        }
    }
}
